/* NPC State Delta record creation: builds a new empty dossier for a name. */
import { inferNpcIdentityKind, makeNpcId } from '../core-identity.js';
import { DEFAULT_RELATIONSHIP, normalizeRelationshipBaseline, normalizeRelationshipEvidence, normalizeRelationshipProgress } from '../core-relationship.js';
import { cleanText } from '../core-text.js';
import { emptyProfileEvidence } from '../core-evidence.js';

export function createNpcRecord(name, existingIds = [], baseline = DEFAULT_RELATIONSHIP) {
    return {
        id: makeNpcId(name, existingIds),
        name: cleanText(name, 120) || 'Unnamed NPC',
        identityKind: inferNpcIdentityKind(name),
        aliases: [],
        role: '',
        species: '',
        gender: '',
        homeBase: '',
        age: '',
        apparentAge: '',
        appearance: '',
        personality: '',
        speech: '',
        background: '',
        relationshipSummary: '',
        mood: '',
        location: '',
        goal: '',
        status: '',
        memories: [],
        mannerisms: [],
        behaviorProfile: [],
        keyRelationships: [],
        profileEvidence: emptyProfileEvidence(),
        present: false,
        worldActive: false,
        lastWorldActiveTurn: 0,
        lifeState: 'unknown',
        lifeStateCertainty: '',
        lifeStateReason: '',
        archived: false,
        archiveReason: '',
        archivedAt: null,
        archiveSourceMessageId: null,
        relationship: normalizeRelationshipBaseline(baseline),
        relationshipProgress: normalizeRelationshipProgress(),
        relationshipMilestones: [],
        relationshipEventHistory: [],
        lastRelationshipChange: { impact: 'none', delta: { trust: 0, affection: 0, desire: 0, tension: 0 }, evidence: normalizeRelationshipEvidence(), reason: '', sourceMessageId: null },
        portrait: null,
        portraitPromptPositive: '',
        portraitPromptNegative: '',
        portraitPromptReplace: false,
        portraitSeed: null,
        createdAt: Date.now(),
        updatedAt: Date.now(),
        lastSeenTurn: 0,
        seenCount: 0,
        manualProfileFields: [],
        retentionProtected: false,
        minor: false,
    };
}
