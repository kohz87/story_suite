// node scripts/sim-band.mjs <sim-results-v8.1.md> [out.js]
//
// Rebuilds tests/v2/lean-rpg/v1/band.fixture.js from the simulator's results file: every cell of scenarios
// A-J (win %, unfinished %, mean exchanges, HP left, tempo, SP and MP left), the role bands with the
// in-band counts, the derived-character sheet and the foe table. Test fixture tooling only. Plain Node.

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const FIXTURE = join(HERE, '..', 'tests', 'v2', 'lean-rpg', 'v1', 'band.fixture.js');

const src = process.argv[2] ?? process.env.SIM_RESULTS;
if (!src) {
    console.error('usage: node scripts/sim-band.mjs <sim-results-v8.1.md> [out.js]');
    process.exit(2);
}
const text = readFileSync(resolve(src), 'utf8');
const rowsOf = block => block.split('\n').filter(l => l.startsWith('|')).slice(2)
    .map(l => l.slice(1, -1).split('|').map(c => c.trim()));
const sections = text.split(/^### /m).slice(1).map(s => ({ title: s.split('\n', 1)[0], rows: rowsOf(s) }));
const num = v => Number(v.replace(/[^\d.\-]/g, ''));

const cells = [];
for (const s of sections.filter(x => /^[A-J]\. /.test(x.title))) {
    for (const r of s.rows) cells.push([s.title[0], r[0], num(r[1]), ...r.slice(2).map(Number)]);
}
const bandSec = sections.find(x => x.title.startsWith('Role band check'));
const bands = bandSec.rows.map(r => {
    const [lo, hi] = r[2].startsWith('<') ? [0, num(r[2]) - 0.01] : r[2].split('-').map(Number);
    return [r[0], r[1], lo, hi, r[r.length - 1]];
});
const manySec = sections.find(x => x.title.startsWith('Role band check, 4-6 foes'));
const bandsMany = manySec.rows.map(r => {
    const [lo, hi] = r[2].startsWith('<') ? [0, num(r[2]) - 0.01] : r[2].split('-').map(Number);
    return [r[0], r[1], lo, hi, r[r.length - 1]];
});
const parts = text.slice(text.indexOf('### Derived characters'));
const [charTable, foeTable] = parts.split(/\n\n(?=\| Foe tier)/);
const sheet = rowsOf(charTable).map(r => {
    const [str, vit, agi, dex, int, wis] = r[2].split(' ').map(Number);
    return [r[0], num(r[1]), str, vit, agi, dex, int, wis, num(r[3]), num(r[4]), num(r[5]), num(r[6]), r[7]];
});
const foes = rowsOf(foeTable).map(r => [r[0], num(r[1]), num(r[2]), num(r[3]), num(r[4].replace('d20+', ''))]);

const sha = createHash('sha256').update(text).digest('hex');
const row = a => `    ${JSON.stringify(a)},`;
const out = [
    '// Role / band table of sim-results-v8.1.md as data (generated by scripts/sim-band.mjs; do not edit by hand).',
    '// cells: [scenario, row, level, win %, unfinished %, mean exchanges, HP % left on wins, tempo per exchange, SP % left, MP % left]',
    '// bands: [scenario, row, low, high, "in band" as counted in the results file]',
    '// bandsMany: 4-6-foe scenarios H-J, LOCKED bands (owner decision 48, 16 Nov), same row shape as bands.',
    '// Encounter rule for v1 (implemented later in C4): an even fight is at most 4 standard foes; elites at most 3 per group.',
    '// sheet: [build, level, STR, VIT, AGI, DEX, INT, WIS, HP, SP, MP, hit bonus, rank text]; foes: [tier, level, HP, damage, roll bonus]',
    `export const BAND_SOURCE_SHA256 = ${JSON.stringify(sha)};`,
    `export const BAND_RUNS = ${text.match(/\((\d+) runs per row/)[1]};`,
    `export const BAND_RUNS_MANY = ${text.match(/\bfoes of one tier \((\d+) runs per row/)[1]};`,
    'export const CELLS = [', ...cells.map(row), '];',
    'export const BANDS = [', ...bands.map(row), '];',
    'export const BANDS_MANY = [', ...bandsMany.map(row), '];',
    'export const SHEET = [', ...sheet.map(row), '];',
    'export const FOES = [', ...foes.map(row), '];',
    '',
].join('\n');
writeFileSync(resolve(process.argv[3] ?? FIXTURE), out);
console.log(`cells ${cells.length}, bands ${bands.length}, bandsMany ${bandsMany.length}, sheet ${sheet.length}, foes ${foes.length}`);
