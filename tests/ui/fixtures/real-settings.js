// Test helper: the real Settings view-model (real host, real Story Director + NPC State, real selectors) at code defaults, and the text of the fixture file made from it.
import { createHost } from '../../../testkit/index.js';
import { BUILTIN_MODULES } from '../../../core/modules-list.js';
import { buildSelectors } from '../../../ui/select/build.js';

const KEEP = ['look', 'people', 'rpg', 'world', 'director', 'money', 'extras', 'models', 'addons', 'tools'];

/** The live path's own call: ui/select/build.js settings(), on a host that starts with the shipped defaults. */
export async function realSettings({ worldEvents = false } = {}) {
  const warn = console.warn;
  console.warn = () => {};
  const host = await createHost({ core: true, modules: BUILTIN_MODULES });
  console.warn = warn;
  host.features.set('story-block.rpg', true); // the RPG and fights page is listed only while the RPG is on: the dump has every page
  if (worldEvents) host.features.set('story-director.world-events', true);
  try { return structuredClone(buildSelectors(() => null, host.sdk).settings()); } finally { host.close(); }
}

const line = v => JSON.stringify(v);

/** The rows of every page the harness draws, one row per line. */
export function renderRealFixture(vm) {
  const rows = KEEP.map(id => `  ${id}: [\n${vm.sections.find(s => s.id === id).rows.map(r => `    ${line(r)},`).join('\n')}\n  ],`).join('\n');
  return `// GENERATED by scripts/ui/gen-fixture-rows.mjs from the real Settings selectors; tests/ui/fixtures/real-rows.test.js fails when it is stale. Do not edit.\n\nexport const REAL_ROWS = {\n${rows}\n};\n`;
}
