import { test } from 'node:test';
import assert from 'node:assert/strict';
import { renderMap } from '../../scripts/codemap/render-map.mjs';

const rows = [
  { path: 'core/a.js', job: 'Does a | b.', exports: ['a(x)', 'B'], imports: ['core/b.js'], importedBy: [], lines: 12, tests: ['tests/a.test.js'] },
  { path: 'core/b.js', job: 'Does b.', exports: [], imports: [], importedBy: ['core/a.js'], lines: 3, tests: [] },
  { path: 'scripts/c.mjs', job: 'Does c.', exports: ['main()'], imports: [], importedBy: [], lines: 40, tests: [] },
];

test('renders a generated header, one section per top folder, one table row per file', () => {
  const md = renderMap(rows);
  assert.ok(md.startsWith('# Code map\n'));
  assert.match(md, /Generated by `npm run codemap`/);
  assert.match(md, /Do not edit by hand/);
  assert.ok(md.indexOf('## core') < md.indexOf('## scripts'));
  assert.match(md, /\| File \| Job \| Exports \| Imports \| Imported by \| Lines \| Tests \|/);
  assert.ok(md.includes('| `core/a.js` | Does a \\| b. | `a(x)`<br>`B` | `core/b.js` | — | 12 | `tests/a.test.js` |'));
  assert.ok(md.includes('| `core/b.js` | Does b. | — | — | `core/a.js` | 3 | — |'));
  assert.ok(md.endsWith('\n'));
});

test('the totals line counts files and lines', () => {
  assert.match(renderMap(rows), /3 files, 55 lines\./);
});

test('rendering is deterministic', () => {
  assert.equal(renderMap(rows), renderMap(rows.slice()));
});
