// A pipe inside a table cell would split the row.
const cell = text => text.replaceAll('|', '\\|');

function formatList(items) {
  return items.length > 0 ? items.map(item => `\`${cell(item)}\``).join('<br>') : '—';
}

/**
 * Renders codemap rows into a deterministic markdown document grouped by top folder.
 */
export function renderMap(rows, { title = 'Code map', source = 'docs/codemap/jobs.json and the source' } = {}) {
  const sorted = rows.slice().sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));

  const sections = new Map();
  for (const row of sorted) {
    const topFolder = row.path.includes('/') ? row.path.split('/')[0] : '(root files)';
    if (!sections.has(topFolder)) sections.set(topFolder, []);
    sections.get(topFolder).push(row);
  }

  const out = [
    `# ${title}`,
    '',
    `Generated by \`npm run codemap\` from ${source}. Do not edit by hand. The maps carry no line counts (the 450-line limit is enforced by the size check).`,
  ];

  for (const folder of Array.from(sections.keys()).sort()) {
    out.push('', `## ${folder}`, '');
    out.push('| File | Job | Exports | Imports | Imported by | Tests |');
    out.push('|---|---|---|---|---|---|');
    for (const row of sections.get(folder)) {
      const job = cell(row.job);
      out.push(
        `| \`${row.path}\` | ${job} | ${formatList(row.exports)} | ${formatList(row.imports)} | ${formatList(row.importedBy)} | ${formatList(row.tests)} |`,
      );
    }
  }

  return out.join('\n') + '\n';
}
