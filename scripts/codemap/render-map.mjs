function formatList(items) {
  return items.length > 0 ? items.map(item => `\`${item}\``).join('<br>') : '—';
}

/**
 * Renders codemap rows into a deterministic markdown document grouped by top folder.
 */
export function renderMap(rows) {
  const sorted = rows.slice().sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
  const totalLines = sorted.reduce((sum, r) => sum + r.lines, 0);

  const sections = new Map();
  for (const row of sorted) {
    const topFolder = row.path.split('/')[0];
    if (!sections.has(topFolder)) sections.set(topFolder, []);
    sections.get(topFolder).push(row);
  }

  const out = [
    '# Code map',
    '',
    'Generated by `npm run codemap` from `docs/codemap/jobs.json` and the source. Do not edit by hand.',
    '',
    `${sorted.length} files, ${totalLines} lines.`,
  ];

  for (const folder of Array.from(sections.keys()).sort()) {
    out.push('', `## ${folder}`, '');
    out.push('| File | Job | Exports | Imports | Imported by | Lines | Tests |');
    out.push('|---|---|---|---|---|---:|---|');
    for (const row of sections.get(folder)) {
      const job = row.job.replaceAll('|', '\\|');
      out.push(
        `| \`${row.path}\` | ${job} | ${formatList(row.exports)} | ${formatList(row.imports)} | ${formatList(row.importedBy)} | ${row.lines} | ${formatList(row.tests)} |`,
      );
    }
  }

  return out.join('\n') + '\n';
}
