// Builds AI-README.md from docs/dev/ai-readme/*.md (hand-written) and the generated tables, or checks it is current.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseModule } from '../codemap/parse-module.mjs';
import { exportNames } from '../codemap/export-names.mjs';
import { generatedTables } from './tables.mjs';

export const PARTS = ['purpose', 'concepts', 'rules', 'modules', 'testing', 'plugin', 'systems', 'ui', 'packs'];
const MARKER = /^<!-- generated:([\w-]+) -->$/gm;
const TITLE = '# Story Suite: AI-README\n\nGenerated by `scripts/ai-readme/build.mjs` from `docs/dev/ai-readme/*.md` and the code. Do not edit it by hand; run `npm run codemap`.\n';
const read = (root, rel) => fs.readFileSync(path.join(root, rel), 'utf8');

/** AI-README.md as it should be: the hand-written parts in order, each marker followed by its table and a closing marker. */
export async function renderReadme(root) {
  const tables = await generatedTables(root);
  const body = PARTS.map(name => read(root, `docs/dev/ai-readme/${name}.md`).trimEnd()).join('\n\n');
  const filled = body.replace(MARKER, (_, name) => {
    if (!(name in tables)) throw new Error(`ai-readme: unknown generated block "${name}"`);
    return `<!-- generated:${name} -->\n${tables[name]}\n<!-- /generated:${name} -->`;
  });
  return `${TITLE}\n${filled}\n`;
}

// Parsed modules by repo path, loaded on demand, so `exportNames` can follow re-exports.
class Modules extends Map {
  constructor(root) { super(); this.root = root; }
  has(rel) { return this.get(rel) !== undefined; }
  get(rel) {
    if (!super.has(rel) && fs.existsSync(path.join(this.root, rel)) && fs.statSync(path.join(this.root, rel)).isFile()) super.set(rel, parseModule(read(this.root, rel)));
    return super.get(rel);
  }
}

/** Problems in the hand-written parts: a backticked file that is missing, or `file#name` whose file does not export `name`. */
export function handWrittenProblems(root) {
  const modules = new Modules(root);
  const files = { has: rel => fs.existsSync(path.join(root, rel)) };
  const problems = [];
  const version = /SUITE_VERSION = '([^']+)'/.exec(read(root, 'core/version.js'))?.[1];
  for (const part of PARTS) {
    const rel = `docs/dev/ai-readme/${part}.md`;
    // A written-out suite version goes stale at the next release: the generated version line is the one place for it.
    for (const [found] of read(root, rel).matchAll(/\b0\.\d+\.\d+\b/g)) if (found !== version) problems.push(`${rel}: names suite version ${found}, but the suite is ${version}; use the generated version line`);
    for (const [, token] of read(root, rel).matchAll(/`([\w@./-]+\.(?:m?js|json|css|md|ya?ml|sh)(?:#[\w$]+)?)`/g)) {
      const [file, name] = token.split('#');
      if (!files.has(file)) problems.push(`${rel}: names a file that does not exist: ${file}`);
      else if (name && !/\.m?js$/.test(file)) problems.push(`${rel}: ${token} names an export of a file that is not JavaScript`);
      else if (name && !exportNames(file, modules, files).names.has(name)) problems.push(`${rel}: ${file} does not export ${name}`);
    }
  }
  return problems;
}

async function main(mode) {
  const root = process.env.AI_README_ROOT ?? path.resolve(import.meta.dirname, '../..');
  const problems = handWrittenProblems(root);
  const text = await renderReadme(root);
  const file = path.join(root, 'AI-README.md');
  for (const problem of problems) console.error(problem);
  if (mode === '--write') {
    fs.writeFileSync(file, text, 'utf8');
    console.log('wrote AI-README.md');
  } else if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text) {
    console.error('AI-README.md is stale: run npm run codemap');
    process.exit(1);
  } else console.log('AI-README.md up to date');
  if (problems.length) process.exit(1);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const mode = process.argv[2];
  if (mode !== '--write' && mode !== '--check') { console.error('usage: node scripts/ai-readme/build.mjs --write|--check'); process.exit(1); }
  await main(mode);
}
